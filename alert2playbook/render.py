"""Markdown rendering of a finished run, for downloads, A2A artifacts and MCP results."""

from __future__ import annotations

from .kb import KnowledgeGraph
from .schemas import PHASES

PHASE_TITLES = {
    "detection_and_analysis": "Detection and analysis",
    "containment": "Containment",
    "eradication": "Eradication",
    "recovery": "Recovery",
    "hardening": "Hardening",
}


def _ref(kb: KnowledgeGraph, ref: str) -> str:
    url = kb.reference_url(ref)
    return f"[{ref}]({url})" if url else ref


def playbook_markdown(state: dict, kb: KnowledgeGraph) -> str:
    pb, triage = state["playbook"], state["triage"]
    lines = [
        f"# {pb['title']}",
        "",
        f"**Severity:** {triage['severity']} ({triage['severity_reason']})  ",
        f"**Platform:** {triage['platform']}",
        "",
        pb["executive_summary"],
        "",
        "## ATT&CK mapping",
        "",
    ]
    for m in state["mapping"]:
        lines.append(f"- {_ref(kb, m['technique_id'])} {m['name']} ({m['confidence']} confidence): `{m['evidence']}`")
    for phase in PHASES:
        lines += ["", f"## {PHASE_TITLES[phase]}", ""]
        for i, step in enumerate(pb.get(phase, []), start=1):
            refs = ", ".join(_ref(kb, r) for r in step.get("references", []))
            lines.append(f"{i}. **{step['action']}.** {step['detail']}" + (f" ({refs})" if refs else ""))
    if pb.get("hunt_leads"):
        lines += ["", "## Hunt leads", ""]
        lines += [f"- **{h['log_source']}**: {h['look_for']}" for h in pb["hunt_leads"]]
    lines += [
        "",
        "---",
        f"Generated by Alert2Playbook on MITRE ATT&CK v{kb.attack_version} and MITRE D3FEND. "
        "Review before acting.",
    ]
    return "\n".join(lines)
